  // 'pl-PL', 'de_AT', 'es-419' -> 'pl', 'de', 'es'; anything unknown -> English
  function pick(locale) {
    var l = String(locale || '').toLowerCase().slice(0, 2);
    return S.hasOwnProperty(l) ? l : 'en';
  }
  // setting: a language code chosen by the user, or anything else ("auto") to follow the TV locale
  function resolve(setting, locale) {
    return typeof setting === 'string' && S.hasOwnProperty(setting) ? setting : pick(locale);
  }
  function t(lang, key, params) {
    var s = (S.hasOwnProperty(lang) ? S[lang] : S.en)[key];
    if (s === undefined) s = S.en[key];
    if (s === undefined) return key;
    return s.replace(/\{(\w+)\}/g, function (m, k) { return params && params[k] !== undefined ? String(params[k]) : m; });
  }

  var api = { langs: LANGS, names: NAMES, strings: S, pick: pick, resolve: resolve, t: t };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.LGTV_I18N = api;
